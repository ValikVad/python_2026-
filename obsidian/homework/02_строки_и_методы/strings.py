def count_words(text: str) -> int:
    """Вернуть количество слов в строке (слова разделены пробелами)."""
    return len(text.split())


def to_slug(title: str) -> str:
    """Привести заголовок к "слагу": нижний регистр, пробелы -> дефисы.

    >>> to_slug("Python Курс 2026")
    "python-курс-2026"
    """
    return title.lower().replace(" ", "-")
